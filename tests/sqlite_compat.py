"""Exercise incoming GSit WAL files and safely rejected layouts in a disposable Pumpkin server."""

import argparse
from contextlib import closing
from pathlib import Path
import shutil
import sqlite3
import subprocess
import sys
import tempfile

from support import LEGACY_DB, boot

PLAYER = "3e96862c-1d7e-4b0a-a535-b12bc6d586cb"


def leave_committed_wal(path, schema):
    """Exit a separate SQLite writer after commit, before its last-close checkpoint."""
    with closing(sqlite3.connect(path)) as db:
        assert db.execute("PRAGMA journal_mode=WAL").fetchone() == ("wal",)
    writer = """
import os, sqlite3, sys
db = sqlite3.connect(sys.argv[1])
db.execute('PRAGMA wal_autocheckpoint=0')
db.executescript(sys.stdin.read())
os._exit(0)
"""
    subprocess.run([sys.executable, "-c", writer, path], input=schema, text=True, check=True)
    assert path.with_suffix(".db-wal").stat().st_size > 32


def fixture(root):
    """Install a copy of the database generated by GSit 3.8.0."""
    path = root / "plugins/data/PumpGsit/data/data.db"
    path.parent.mkdir(parents=True)
    shutil.copyfile(LEGACY_DB, path)
    return path


def accept(server, component, root):
    """Recover an actual outstanding exception, keep extensions, and retain writes across restarts."""
    path = fixture(root)
    leave_committed_wal(path, f"""
        BEGIN;
        ALTER TABLE gsit_sit_toggle RENAME TO previous;
        CREATE TABLE "GSit_Sit_Toggle"("UUID" text);
        INSERT INTO Gsit_Sit_Toggle SELECT * FROM previous;
        DROP TABLE previous;
        DROP TABLE gsit_player_toggle;
        CREATE TABLE observed(id TEXT);
        CREATE INDEX by_player ON gsit_sit_toggle(uuid);
        CREATE TRIGGER record_insert AFTER INSERT ON gsit_sit_toggle
            BEGIN INSERT INTO observed VALUES (new.uuid); END;
        PRAGMA application_id=1978;
        PRAGMA user_version=21;
        INSERT INTO gsit_sit_toggle VALUES ('{PLAYER}');
        COMMIT;
    """)
    # Immutable opens only the base file, demonstrating that the committed row requires the WAL.
    with closing(sqlite3.connect(f"{path.as_uri()}?immutable=1", uri=True)) as db:
        assert db.execute("SELECT uuid FROM gsit_sit_toggle WHERE uuid=?", (PLAYER,)).fetchall() == []
        assert db.execute("PRAGMA user_version").fetchone() == (0,)
    with boot(server, component, root, "incoming-wal") as command:
        command(f"sit toggle {PLAYER}", "have enabled")
        for _ in range(2):
            command(f"sit toggle {PLAYER} off", "have disabled")
    with closing(sqlite3.connect(path)) as db:
        assert db.execute("PRAGMA user_version").fetchone() == (21,)
        assert db.execute("PRAGMA application_id").fetchone() == (1978,)
        assert db.execute("PRAGMA journal_mode").fetchone() == ("wal",)
        assert db.execute("SELECT uuid FROM gsit_sit_toggle WHERE uuid=?", (PLAYER,)).fetchall() == [(PLAYER,)] * 2
        assert db.execute("SELECT * FROM observed").fetchall() == [(PLAYER,)] * 3
        assert db.execute("SELECT * FROM gsit_player_toggle").fetchall() == []
        assert db.execute("SELECT name FROM sqlite_schema WHERE name='by_player'").fetchall() == [("by_player",)]
        assert db.execute("PRAGMA integrity_check").fetchall() == [("ok",)]
    with boot(server, component, root, "restart") as command:
        command(f"sit toggle {PLAYER}", "have enabled")
    with closing(sqlite3.connect(path)) as db:
        assert db.execute("SELECT uuid FROM gsit_sit_toggle WHERE uuid=?", (PLAYER,)).fetchall() == []


def reject(server, component, root):
    """Verify neither incoming frames nor other tables change when a layout is unknown."""
    path = fixture(root)
    leave_committed_wal(path, """
        BEGIN;
        DROP TABLE gsit_sit_toggle;
        ALTER TABLE gsit_crawl_toggle ADD COLUMN unknown_field BLOB;
        COMMIT;
    """)
    before = {entry.name: entry.read_bytes() for entry in path.parent.iterdir()}
    with boot(server, component, root, "rejected", expected="gsit_crawl_toggle: expected one writable uuid TEXT column"):
        pass
    after = {entry.name: entry.read_bytes() for entry in path.parent.iterdir()}
    assert before == after


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("server", type=lambda value: Path(value).resolve())
    parser.add_argument("component", type=lambda value: Path(value).resolve())
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="PumpGsit-sqlite-") as directory:
        root = Path(directory)
        accept(args.server, args.component, root / "wal")
        reject(args.server, args.component, root / "unknown")
    print("Passed incoming WAL, missing table, equivalent DDL, schema extensions and rejection rollback.")
